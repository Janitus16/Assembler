; * CROSSROAD 
; * El jugador sube infinitamente y se mueve lateralmente.

SGROUP      GROUP   CODE_SEG, DATA_SEG
            ASSUME  CS:SGROUP, DS:SGROUP, SS:SGROUP

    TRUE  EQU 1
    FALSE EQU 0

    ; Teclas
    ASCII_SPECIAL_KEY EQU 00
    ASCII_LEFT        EQU 04Bh
    ASCII_RIGHT       EQU 04Dh
    ASCII_QUIT        EQU 071h ; 'q'

    ; Gráficos
    ASCII_PLAYER      EQU 02Ah ; '*'
    ATTR_PLAYER       EQU 00Fh ; Blanco brillante
    ASCII_FIELD       EQU 0DBh ; Bloque para paredes
    ATTR_FIELD        EQU 007h ; Gris

    CURSOR_SIZE_HIDE  EQU 02607h
    SCREEN_MAX_ROWS   EQU 25
    SCREEN_MAX_COLS   EQU 80

    ; Límites de carretera
    FIELD_C1 EQU 25
    FIELD_C2 EQU 55

CODE_SEG    SEGMENT PUBLIC
            ORG 100h

MAIN    PROC    NEAR
    MAIN_GO:
        CALL REGISTER_TIMER_INTERRUPT
        CALL INIT_GAME
        CALL INIT_SCREEN
        CALL HIDE_CURSOR
        CALL DRAW_WALLS

        ; Posición inicial: Fila 23, Columna central
        MOV DH, 23
        MOV DL, 40
        CALL MOVE_CURSOR
        
    MAIN_LOOP:
        CMP [END_GAME], TRUE
        JZ END_PROG

        ; Leer teclado (sin bloqueo)
        MOV AH, 0Bh
        INT 21h
        CMP AL, 0
        JZ MAIN_LOOP

        CALL READ_CHAR      
        CMP AL, ASCII_QUIT
        JZ END_PROG
        
        CMP AL, ASCII_SPECIAL_KEY
        JNZ MAIN_LOOP
        
        CALL READ_CHAR ; Lee el código de la flecha
        
        CMP AL, ASCII_LEFT
        JZ LEFT_KEY
        CMP AL, ASCII_RIGHT
        JZ RIGHT_KEY
        JMP MAIN_LOOP

    LEFT_KEY:
        MOV [INC_COL], -1
        JMP MAIN_LOOP

    RIGHT_KEY:
        MOV [INC_COL], 1
        JMP MAIN_LOOP

    END_PROG:
        CALL RESTORE_TIMER_INTERRUPT
        MOV AX, 3   ; Limpiar pantalla al salir
        INT 10h
        INT 20h     
MAIN    ENDP    

; --- DIBUJAR PAREDES ---
DRAW_WALLS PROC NEAR
    MOV DH, 0
    WALL_LOOP:
        MOV DL, FIELD_C1
        CALL MOVE_CURSOR
        MOV AL, ASCII_FIELD
        MOV BL, ATTR_FIELD
        CALL PRINT_CHAR_ATTR

        MOV DL, FIELD_C2
        CALL MOVE_CURSOR
        CALL PRINT_CHAR_ATTR

        INC DH
        CMP DH, SCREEN_MAX_ROWS
        JNE WALL_LOOP
    RET
DRAW_WALLS ENDP

; --- INTERRUPCIÓN DEL RELOJ ---
NEW_TIMER_INTERRUPT PROC NEAR
    PUSHF
    CALL DWORD PTR [OLD_INTERRUPT_BASE]
    
    PUSH AX
    PUSH BX
    PUSH CX
    PUSH DX

    INC [INT_COUNT]
    MOV AL, [INT_COUNT]
    CMP [DIV_SPEED], AL
    JNZ END_ISR
    MOV [INT_COUNT], 0

    ; Obtener posición actual del jugador
    CALL GET_CURSOR_PROP 

    ; Aplicar movimiento lateral y resetear
    MOV AL, [INC_COL]
    ADD DL, AL
    MOV [INC_COL], 0 

    ; Lógica de colisión lateral
    CMP DL, FIELD_C1
    JBE COLLISION
    CMP DL, FIELD_C2
    JAE COLLISION

    ; Movimiento infinito hacia arriba
    DEC DH
    CMP DH, 0
    JNZ CONTINUE_MOVE
    MOV DH, SCREEN_MAX_ROWS - 1 

CONTINUE_MOVE:
    CALL MOVE_CURSOR
    MOV AL, ASCII_PLAYER
    MOV BL, ATTR_PLAYER
    CALL PRINT_CHAR_ATTR
    JMP END_ISR

COLLISION:
    MOV [END_GAME], TRUE

END_ISR:
    POP DX
    POP CX
    POP BX
    POP AX
    IRET
NEW_TIMER_INTERRUPT ENDP

; --- FUNCIONES AUXILIARES ---

INIT_GAME PROC NEAR
    MOV [INC_COL], 0
    MOV [DIV_SPEED], 3 
    MOV [INT_COUNT], 0
    MOV [END_GAME], FALSE
    RET
INIT_GAME ENDP

INIT_SCREEN PROC NEAR
    MOV AX, 0003h
    INT 10h
    RET
INIT_SCREEN ENDP

READ_CHAR PROC NEAR
    MOV AH, 08h
    INT 21h
    RET
READ_CHAR ENDP

PRINT_CHAR_ATTR PROC NEAR
    MOV AH, 09h
    MOV BH, 0
    MOV CX, 1
    INT 10h
    RET
PRINT_CHAR_ATTR ENDP

HIDE_CURSOR PROC NEAR
    MOV AH, 01h
    MOV CX, CURSOR_SIZE_HIDE
    INT 10h
    RET
HIDE_CURSOR ENDP

GET_CURSOR_PROP PROC NEAR
    MOV AH, 03h
    XOR BX, BX
    INT 10h
    RET
GET_CURSOR_PROP ENDP

SET_CURSOR_PROP PROC NEAR
    MOV AH, 02h
    XOR BX, BX
    INT 10h
    RET
SET_CURSOR_PROP ENDP

MOVE_CURSOR PROC NEAR
    CALL SET_CURSOR_PROP
    RET
MOVE_CURSOR ENDP

REGISTER_TIMER_INTERRUPT PROC NEAR
    PUSH DS
    MOV AX, 3508h
    INT 21h
    MOV WORD PTR [OLD_INTERRUPT_BASE], BX
    MOV WORD PTR [OLD_INTERRUPT_BASE+2], ES
    
    MOV AX, 2508h
    MOV DX, OFFSET NEW_TIMER_INTERRUPT
    INT 21h
    POP DS
    RET
REGISTER_TIMER_INTERRUPT ENDP

RESTORE_TIMER_INTERRUPT PROC NEAR
    PUSH DS
    LDS DX, DWORD PTR [OLD_INTERRUPT_BASE]
    MOV AX, 2508h
    INT 21h
    POP DS
    RET
RESTORE_TIMER_INTERRUPT ENDP

CODE_SEG ENDS

DATA_SEG SEGMENT PUBLIC
    ; Usamos DD para que LDS DX pueda leer los 32 bits (segmento:offset) sin error
    OLD_INTERRUPT_BASE DD 0 
    INC_COL   DB 0
    DIV_SPEED DB 0
    INT_COUNT DB 0
    END_GAME  DB 0
DATA_SEG ENDS

END MAIN