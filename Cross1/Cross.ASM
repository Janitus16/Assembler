SGROUP      GROUP   CODE_SEG, DATA_SEG
            ASSUME  CS:SGROUP, DS:SGROUP, SS:SGROUP

    ; --- CONSTANTES ---
    TRUE  EQU 1
    FALSE EQU 0

    ASCII_SPECIAL_KEY EQU 00
    ASCII_LEFT        EQU 04Bh
    ASCII_RIGHT       EQU 04Dh
    ASCII_UP          EQU 048h
    ASCII_QUIT        EQU 071h 

    ASCII_PLAYER      EQU 02Ah 
    ATTR_PLAYER       EQU 00Fh 
    ASCII_WALL        EQU 0DBh 
    
    CURSOR_SIZE_HIDE  EQU 02607h
    SCREEN_MAX_ROWS   EQU 25

    FIELD_C1 EQU 25
    FIELD_C2 EQU 55

    COLOR_VERDE     EQU 02h
    COLOR_CARRETERA EQU 08h
    COLOR_AGUA      EQU 03h

CODE_SEG    SEGMENT PUBLIC
            ORG 100h

MAIN    PROC    NEAR
    MOV AX, CS
    MOV DS, AX

    CALL REGISTER_TIMER_INTERRUPT
    CALL INIT_GAME
    CALL INIT_SCREEN
    CALL HIDE_CURSOR
    CALL DRAW_INITIAL_MAP 

    MOV BYTE PTR [POS_R], 20
    MOV BYTE PTR [POS_C], 40
        
MAIN_LOOP:
    CMP BYTE PTR [END_GAME], TRUE
    JE JUMP_TO_END
    MOV AH, 0Bh
    INT 21h
    CMP AL, 0
    JE MAIN_LOOP 
    CALL READ_CHAR      
    CMP AL, ASCII_QUIT
    JE JUMP_TO_END
    CMP AL, ASCII_SPECIAL_KEY
    JNE MAIN_LOOP
    CALL READ_CHAR 
    CMP AL, ASCII_LEFT
    JE LEFT_KEY
    CMP AL, ASCII_RIGHT
    JE RIGHT_KEY
    CMP AL, ASCII_UP
    JE UP_KEY
    JMP MAIN_LOOP

JUMP_TO_END: JMP END_PROG

LEFT_KEY:   MOV BYTE PTR [INC_COL], -1
            JMP MAIN_LOOP
RIGHT_KEY:  MOV BYTE PTR [INC_COL], 1
            JMP MAIN_LOOP
UP_KEY:     MOV BYTE PTR [INC_ROW], -1
            JMP MAIN_LOOP

END_PROG:
    CALL RESTORE_TIMER_INTERRUPT
    MOV AX, 0003h 
    INT 10h
    INT 20h     
MAIN    ENDP    

NEW_TIMER_INTERRUPT PROC NEAR
    PUSHF
    CALL DWORD PTR [OLD_INTERRUPT_BASE] 
    PUSH AX
    PUSH BX
    PUSH CX
    PUSH DX
    PUSH DS
    MOV AX, CS
    MOV DS, AX

    INC BYTE PTR [INT_COUNT]
    MOV AL, BYTE PTR [INT_COUNT]
    CMP AL, BYTE PTR [DIV_SPEED]
    JE DO_LOGIC
    JMP EXIT_ISR 

DO_LOGIC:
    MOV BYTE PTR [INT_COUNT], 0

    ; 1. Borrar rastro
    MOV DH, BYTE PTR [POS_R]
    MOV DL, BYTE PTR [POS_C]
    CALL MOVE_CURSOR
    MOV AL, ' '
    MOV BL, 0
    CALL PRINT_CHAR_ATTR

    ; 2. Actualizar posición
    MOV AL, BYTE PTR [INC_COL]
    ADD BYTE PTR [POS_C], AL
    MOV AL, BYTE PTR [INC_ROW]
    ADD BYTE PTR [POS_R], AL
    MOV BYTE PTR [INC_COL], 0
    MOV BYTE PTR [INC_ROW], 0

    ; 3. Scroll y Actualización de Memoria de Terreno
    CMP BYTE PTR [POS_R], 5
    JAE SKIP_SCROLL
    
    ; Scroll físico
    MOV AX, 0701h   
    MOV BH, 07h     
    XOR CX, CX
    MOV DX, 184Fh 
    INT 10h
    MOV BYTE PTR [POS_R], 6 

    ; Scroll lógico: Desplazar el array de tipos de suelo hacia abajo
    MOV SI, 23
SHIFT_ARRAY:
    MOV AL, [LINE_TYPES + SI]
    MOV [LINE_TYPES + SI + 1], AL
    DEC SI
    CMP SI, -1
    JNE SHIFT_ARRAY

    ; Generar nueva línea arriba
    INC BYTE PTR [MAP_LINE_COUNT]
    CALL UPDATE_MAP_COLOR ; Actualiza CURRENT_COLOR según la secuencia
    MOV AL, BYTE PTR [CURRENT_COLOR]
    MOV [LINE_TYPES], AL

    ; Dibujar la nueva fila 0
    MOV BL, AL
    MOV AL, ASCII_WALL
    CMP BL, COLOR_VERDE
    JE DRAW_G
    ; Carretera/Agua
    MOV DH, 0
    MOV DL, 0
    CALL MOVE_CURSOR
    MOV CX, 80
    CALL PRINT_MULTIPLE_CHAR
    JMP SKIP_SCROLL
DRAW_G:
    MOV DH, 0
    MOV DL, 0
    CALL MOVE_CURSOR
    MOV CX, FIELD_C1
    CALL PRINT_MULTIPLE_CHAR
    MOV DL, FIELD_C2
    CALL MOVE_CURSOR
    MOV CX, 25
    CALL PRINT_MULTIPLE_CHAR

SKIP_SCROLL:
    ; 4. LÓGICA DE COLISIÓN REAL (Basada en la fila donde está el jugador)
    XOR BX, BX
    MOV BL, BYTE PTR [POS_R]
    MOV AL, [LINE_TYPES + BX] ; Obtener tipo de suelo de esa fila exacta

    CMP AL, COLOR_VERDE
    JNE DRAW_PLAYER ; Si no es verde (es carretera o agua), no muere lateralmente

    ; Si la fila es verde, chequear columnas
    MOV AL, BYTE PTR [POS_C]
    CMP AL, FIELD_C1
    JB TRIGGER_COLLISION
    CMP AL, FIELD_C2
    JAE TRIGGER_COLLISION

DRAW_PLAYER:
    MOV DH, BYTE PTR [POS_R]
    MOV DL, BYTE PTR [POS_C]
    CALL MOVE_CURSOR
    MOV AL, ASCII_PLAYER
    MOV BL, ATTR_PLAYER
    CALL PRINT_CHAR_ATTR
    JMP EXIT_ISR

TRIGGER_COLLISION:
    MOV BYTE PTR [END_GAME], TRUE

EXIT_ISR:
    POP DS
    POP DX
    POP CX
    POP BX
    POP AX
    IRET
NEW_TIMER_INTERRUPT ENDP

UPDATE_MAP_COLOR PROC NEAR
    MOV AL, BYTE PTR [MAP_LINE_COUNT]
    CMP AL, 10
    JB ES_VERDE
    CMP AL, 30
    JB ES_CARRETERA
    CMP AL, 40
    JB ES_VERDE
    CMP AL, 60
    JB ES_CARRETERA
    CMP AL, 70
    JB ES_VERDE
    CMP AL, 90
    JB ES_AGUA
    MOV BYTE PTR [MAP_LINE_COUNT], 0
ES_VERDE:
    MOV BYTE PTR [CURRENT_COLOR], COLOR_VERDE
    RET
ES_CARRETERA:
    MOV BYTE PTR [CURRENT_COLOR], COLOR_CARRETERA
    RET
ES_AGUA:
    MOV BYTE PTR [CURRENT_COLOR], COLOR_AGUA
    RET
UPDATE_MAP_COLOR ENDP

PRINT_MULTIPLE_CHAR PROC NEAR
    MOV AH, 09h
    XOR BH, BH
    INT 10h
    RET
PRINT_MULTIPLE_CHAR ENDP

DRAW_INITIAL_MAP PROC NEAR
    MOV BYTE PTR [TEMP_R], 0
LOOP_M:
    MOV BL, COLOR_VERDE
    XOR AX, AX
    MOV AL, BYTE PTR [TEMP_R]
    MOV DI, AX
    MOV [LINE_TYPES + DI], BL ; Llenar memoria inicial como verde
    
    MOV DH, BYTE PTR [TEMP_R]
    MOV DL, 0
    CALL MOVE_CURSOR
    MOV AL, ASCII_WALL
    MOV CX, FIELD_C1
    CALL PRINT_MULTIPLE_CHAR
    MOV DL, FIELD_C2
    CALL MOVE_CURSOR
    MOV CX, 25
    CALL PRINT_MULTIPLE_CHAR
    INC BYTE PTR [TEMP_R]
    CMP BYTE PTR [TEMP_R], 25
    JNE LOOP_M
    RET
DRAW_INITIAL_MAP ENDP

INIT_GAME PROC NEAR
    MOV BYTE PTR [MAP_LINE_COUNT], 0
    MOV BYTE PTR [CURRENT_COLOR], COLOR_VERDE
    MOV BYTE PTR [DIV_SPEED], 2 
    MOV BYTE PTR [END_GAME], FALSE
    RET
INIT_GAME ENDP

INIT_SCREEN PROC NEAR
    MOV AX, 0003h 
    INT 10h
    RET
INIT_SCREEN ENDP

HIDE_CURSOR PROC NEAR
    MOV AH, 01h
    MOV CX, CURSOR_SIZE_HIDE
    INT 10h
    RET
HIDE_CURSOR ENDP

MOVE_CURSOR PROC NEAR
    PUSH AX
    PUSH BX
    MOV AH, 02h
    XOR BX, BX
    INT 10h
    POP BX
    POP AX
    RET
MOVE_CURSOR ENDP

PRINT_CHAR_ATTR PROC NEAR
    PUSH AX
    PUSH CX
    MOV AH, 09h
    XOR BH, BH
    MOV CX, 0001h
    INT 10h
    POP CX
    POP AX
    RET
PRINT_CHAR_ATTR ENDP

READ_CHAR PROC NEAR
    MOV AH, 08h 
    INT 21h
    RET
READ_CHAR ENDP

REGISTER_TIMER_INTERRUPT PROC NEAR
    MOV AX, 3508h 
    INT 21h
    MOV WORD PTR [OLD_INTERRUPT_BASE + 2], ES
    MOV WORD PTR [OLD_INTERRUPT_BASE], BX
    MOV AX, 2508h 
    MOV DX, OFFSET NEW_TIMER_INTERRUPT
    INT 21h
    RET
REGISTER_TIMER_INTERRUPT ENDP

RESTORE_TIMER_INTERRUPT PROC NEAR
    PUSH DS
    MOV DX, WORD PTR [OLD_INTERRUPT_BASE]
    MOV DS, WORD PTR [OLD_INTERRUPT_BASE + 2]
    MOV AX, 2508h
    INT 21h
    POP DS
    RET
RESTORE_TIMER_INTERRUPT ENDP

CODE_SEG ENDS

DATA_SEG SEGMENT PUBLIC
    OLD_INTERRUPT_BASE DW 0, 0
    INC_COL    DB 0
    INC_ROW    DB 0
    POS_R      DB 0
    POS_C      DB 0
    DIV_SPEED  DB 0
    INT_COUNT  DB 0
    END_GAME   DB 0
    MAP_LINE_COUNT DB 0  
    CURRENT_COLOR  DB 0  
    TEMP_R         DB 0
    LINE_TYPES     DB 26 DUP(0) ; Memoria de qué hay en cada fila
DATA_SEG ENDS

END MAIN